#!/usr/bin/env node

// `NOTICE` is a generated artifact: it lists every package npm installs with `--omit=dev`,
// read from `package-lock.json` alone. The generator never looks at `node_modules`, so it
// runs in a fresh worktree, and the test in this folder fails the gate when the committed
// file drifts from the lockfile.

import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const NOTICE_HEADER = `Codebox
Third-party notices for the production dependency tree.

Generated by scripts/legal/notice.mjs from package-lock.json. Do not edit by hand.

This distribution includes the following third-party packages:
`;

// A copyleft-only dependency ships only with a written exception, and every key must name a
// package in the production tree. An empty map means the tree carries none.
export const COPYLEFT_EXCEPTIONS = Object.freeze({});

// Fallbacks for a locked entry that declares no SPDX identifier. Empty today: the lockfile
// carries one for every production package, and the test refuses `UNKNOWN`.
export const LICENSE_OVERRIDES = Object.freeze({});

const COPYLEFT_ONLY = /^(A?GPL|LGPL|SSPL)(-[0-9][0-9A-Za-z.+-]*)?(-ONLY|-OR-LATER)?$/;

function compare(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function stripParens(value) {
  let text = value;
  while (text.startsWith('(') && text.endsWith(')')) {
    text = text.slice(1, -1).trim();
  }
  return text;
}

function licenseOf(name, entry) {
  if (typeof entry.license === 'string') return entry.license;
  if (entry.license && typeof entry.license === 'object' && typeof entry.license.type === 'string') {
    return entry.license.type;
  }
  if (typeof LICENSE_OVERRIDES[name] === 'string') return LICENSE_OVERRIDES[name];
  return 'UNKNOWN';
}

/**
 * Production scan rule: walk `lockfile.packages` and keep an entry only when its key contains
 * `node_modules/` (so the root, the workspaces and every link are out), `link !== true`,
 * `dev !== true` and `version` is a string. `devOptional` entries stay: npm still installs an
 * optional dependency of a production package when only dev dependencies are omitted. The
 * name is the text after the last `node_modules/`, so a nested copy keeps its own name.
 * Duplicates collapse on `name@version`.
 */
export function collectProductionPackages(lockfile) {
  const entries = lockfile && typeof lockfile === 'object' && lockfile.packages ? lockfile.packages : {};
  const seen = new Set();
  const packages = [];
  for (const [key, entry] of Object.entries(entries)) {
    if (!key.includes('node_modules/')) continue;
    if (!entry || typeof entry !== 'object') continue;
    if (entry.link === true) continue;
    if (entry.dev === true) continue;
    if (typeof entry.version !== 'string') continue;
    const name = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
    const id = `${name}@${entry.version}`;
    if (seen.has(id)) continue;
    seen.add(id);
    packages.push({ name, version: entry.version, license: licenseOf(name, entry) });
  }
  return packages.sort((a, b) => compare(a.name, b.name) || compare(a.version, b.version));
}

/**
 * Copyleft-only rule: upper-case the identifier, strip surrounding parentheses, drop a
 * `WITH …` suffix and split an `OR` expression into alternatives. The licence is copyleft-only
 * when every alternative is GPL, AGPL, LGPL or SSPL, with an optional version and
 * `-only`/`-or-later`. Weak and file-level licences (MPL, EPL, CDDL, CC-BY, BlueOak, Unlicense,
 * ISC, Apache, MIT) are recorded with their identifier, never as exceptions.
 */
export function isCopyleftOnly(license) {
  if (typeof license !== 'string') return false;
  const normalised = stripParens(license.trim().toUpperCase());
  const withoutWith = normalised.split(/\s+WITH\s+/)[0].trim();
  const alternatives = withoutWith
    .split(/\s+OR\s+/)
    .map((alternative) => alternative.trim())
    .filter((alternative) => alternative.length > 0);
  if (alternatives.length === 0) return false;
  return alternatives.every((alternative) => COPYLEFT_ONLY.test(alternative));
}

function readCommittedNotice() {
  try {
    return readFileSync(new URL('../../NOTICE', import.meta.url), 'utf8');
  } catch {
    return '';
  }
}

function exceptionReason(name) {
  const reason = COPYLEFT_EXCEPTIONS[name];
  return typeof reason === 'string' && reason.length > 0 ? reason : null;
}

export function renderNotice(packages) {
  const list = Array.isArray(packages) ? packages : [];
  const packageLines = list.map((pkg) => {
    const reason = exceptionReason(pkg.name);
    const suffix = reason === null ? '' : ` — exception: ${reason}`;
    return `- ${pkg.name}@${pkg.version} — ${pkg.license}${suffix}`;
  });
  const exceptions = list
    .filter((pkg) => exceptionReason(pkg.name) !== null)
    .map((pkg) => `- ${pkg.name}@${pkg.version} — ${pkg.license} — ${exceptionReason(pkg.name)}`);
  const exceptionLines = exceptions.length === 0 ? '(none)' : exceptions.join('\n');
  return `${NOTICE_HEADER}\n${packageLines.join('\n')}\n\nCopyleft exceptions\n-------------------\n${exceptionLines}\n`;
}

export function checkNotice(packages, bytes) {
  return typeof bytes === 'string' && bytes === renderNotice(packages);
}

export async function main(argv) {
  const args = Array.isArray(argv) ? argv.filter((arg) => arg !== undefined) : [];
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    process.stderr.write('usage: node scripts/legal/notice.mjs [--check]\n');
    return 2;
  }

  const lockfile = JSON.parse(readFileSync(new URL('../../package-lock.json', import.meta.url), 'utf8'));
  const packages = collectProductionPackages(lockfile);
  const expected = renderNotice(packages);

  if (args[0] === '--check') {
    if (!checkNotice(packages, readCommittedNotice())) {
      process.stderr.write('NOTICE is stale: run node scripts/legal/notice.mjs\n');
      return 1;
    }
    return 0;
  }

  writeFileSync(new URL('../../NOTICE', import.meta.url), expected);
  process.stdout.write(`wrote NOTICE (${packages.length} packages)\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).then((code) => {
    process.exitCode = code;
  });
}
