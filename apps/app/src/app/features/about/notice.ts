export interface ThirdPartyNotice {
  readonly name: string;
  readonly version: string;
  readonly licence: string;
  readonly label: string;
}

const BULLET = '- ';
const SEPARATOR = ' — ';
const END_OF_PACKAGES = 'Copyleft exceptions';

