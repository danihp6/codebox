export function parseNotice(text: string): readonly ThirdPartyNotice[] {
  const notices: ThirdPartyNotice[] = [];
  for (const line of text.split('\n')) {
    if (line.startsWith(END_OF_PACKAGES)) break;
    if (!line.startsWith(BULLET)) continue;

    const parts = line.slice(BULLET.length).split(SEPARATOR);
    if (parts.length !== 2) continue;

    const label = (parts[0] ?? '').trim();
    const licence = (parts[1] ?? '').trim();
    if (label === '' || licence === '') continue;

    const at = label.lastIndexOf('@');
    if (at <= 0) continue;

    const name = label.slice(0, at).trim();
    const version = label.slice(at + 1).trim();
    if (name === '' || version === '') continue;

    notices.push({ name, version, licence, label: `${name}@${version}` });
  }
  return notices;
}

export const THIRD_PARTY_NOTICES: readonly ThirdPartyNotice[] = Object.freeze(
  parseNotice(NOTICE_TEXT),
);
